/** End-to-end Beacon onboarding and simulated trip regression. */
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.BEACON_URL || 'http://localhost:3000';
const output = 'docs/ui-research/beacon-flow';
await mkdir(output, { recursive: true });
const context = await browser.newContext({ viewport: { width:390, height:844 }, reducedMotion:'reduce' });
const page = await context.newPage();
const errors=[];
async function fixture(){await page.goto(`${base}/demo?walkthrough=1&transport=fixture`);await page.getByRole('button',{name:'Get me home',exact:true}).waitFor();}
page.on('pageerror', e=>errors.push(e.message));
page.on('console',message=>{if(message.type()==='error') errors.push(message.text());});
async function capture(name) {
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:`${output}/${name}.png`,fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${name}: horizontal overflow`);
}
try {
  await page.goto(base);
  await page.getByRole('link',{name:/Get Started/i}).click();
  await page.getByRole('button',{name:/Set as home/i}).click();
  await page.getByRole('heading',{name:'Your way home.'}).waitFor();
  await capture('01-preferences');
  const budget=page.getByRole('spinbutton');
  await page.getByRole('slider').focus();
  await page.keyboard.press('End');
  assert.equal(await budget.inputValue(),'100');
  await page.keyboard.press('Home');
  await page.keyboard.press('ArrowRight');
  assert.equal(await budget.inputValue(),'1');
  await page.getByRole('switch',{name:'Less walking'}).click();
  assert.equal(await page.getByRole('switch',{name:'Less walking'}).getAttribute('aria-checked'),'false');
  await page.getByRole('switch',{name:'Less walking'}).click();
  await budget.fill('17');
  await page.getByRole('button',{name:/Save and continue/i}).click();
  await page.getByRole('button',{name:/Get me home/i}).waitFor();
  await fixture();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('safecircle.profile.v1')).maxBudget),17);
  await capture('02-home');
  await page.getByRole('button',{name:/Get me home/i}).click();
  await page.getByRole('button',{name:/Cancel/i}).waitFor();
  await capture('03-finding');
  await page.getByRole('button',{name:/Cancel/i}).click();
  await page.getByRole('button',{name:/Get me home/i}).click();
  await page.getByRole('button',{name:/Confirm this plan/i}).waitFor({timeout:15000});
  await capture('04-recommendation');
  await page.getByRole('button',{name:'See other options'}).click();
  await page.getByRole('heading',{name:'Other options'}).waitFor();
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('button',{name:'See other options'}).click();
  await page.getByRole('button',{name:/Confirm this plan/i}).click();
  await page.getByTestId('screen-verifying-initial').waitFor();
  await capture('05-verifying');
  await page.getByTestId('screen-in-trip-initial').waitFor({timeout:45000});
  await page.getByRole('button',{name:'I’m home',exact:true}).click();
  await page.getByTestId('screen-arrival').waitFor();
  await capture('06-arrival');
  await page.getByRole('button',{name:'Finish',exact:true}).click();
  await page.getByRole('button',{name:/Get me home/i}).waitFor();
  await fixture();
  await page.getByRole('button',{name:/Get me home/i}).waitFor();
  for(const width of [320,1440]) {
    await page.setViewportSize({width,height:width===320?568:1000});
    await page.waitForTimeout(150);
    await capture(`home-${width}`);
    const cta=await page.getByRole('button',{name:/Get me home/i}).boundingBox();
    assert(cta && cta.y>=0 && cta.y+cta.height<=(width===320?568:1000),'Primary action stays visible');
  }
  // Reloaded preferences and recovery from unavailable browser storage.
  await page.goto(`${base}/onboarding/preferences`);
  await page.getByRole('spinbutton').waitFor();
  assert.equal(await page.getByRole('spinbutton').inputValue(),'17');
  await page.getByRole('spinbutton').fill('101');
  assert(await page.getByRole('button',{name:/Save and continue/i}).isDisabled());
  await page.getByRole('spinbutton').fill('3');
  await page.getByRole('button',{name:/Save and continue/i}).click();
  await page.getByRole('button',{name:/Get me home/i}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${base}/onboarding/preferences`);
  await page.getByRole('spinbutton').fill('0');
  await page.getByRole('button',{name:/Save and continue/i}).click();
  await fixture();
  await page.getByRole('button',{name:/Get me home/i}).click();
  await page.getByTestId('screen-no-options').waitFor({timeout:15000});
  await page.getByRole('button',{name:'Change preferences'}).click();
  await page.getByLabel('Standard walking',{exact:true}).check();
  await page.getByRole('button',{name:'Save changes'}).click();
  await page.getByRole('button',{name:/Get me home/i}).click();
  await page.getByRole('button',{name:'Confirm walking plan'}).waitFor({timeout:15000});
  assert.equal(await page.getByText('Pickup',{exact:true}).count(),0);
  await capture('07-walking');
  await page.getByRole('button',{name:'Confirm walking plan'}).click();
  await page.getByTestId('screen-in-trip-initial').waitFor();
  const privateContext=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await privateContext.addInitScript(()=>{
    for(const key of ['localStorage','sessionStorage']) Object.defineProperty(window,key,{get(){throw new DOMException('Blocked','SecurityError');}});
  });
  const privatePage=await privateContext.newPage();
  privatePage.on('pageerror',e=>errors.push(e.message));
  await privatePage.goto(`${base}/onboarding/welcome`);
  await privatePage.getByRole('link',{name:/Get Started/i}).click();
  await privatePage.getByRole('button',{name:/Set as home/i}).click();
  await privatePage.getByRole('button',{name:/Save and continue/i}).click();
  await privatePage.getByRole('button',{name:/Get me home/i}).waitFor();
  await privatePage.getByText('Storage unavailable: keep this tab open to retain the trip identifier.').waitFor();
  await privateContext.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: onboarding, exact budget, save, search, cancel, recommendation, verification, arrival, returner, 320/390/1440px.');
} finally { await browser.close(); }
